-- =====================================================================
--  Migration 002: add user_sessions for persistent session tokens
--  -------------------------------------------------------------------
--  Stores cryptographically secure SHA-256 hashes of bearer session
--  tokens, user ID, role, expiration, and revocation status.
--
--  Idempotent: re-running is safe (uses IF NOT EXISTS).
--  Non-destructive: does NOT drop or alter existing tables.
-- =====================================================================

CREATE TABLE IF NOT EXISTS user_sessions (
    session_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash      VARCHAR(64) NOT NULL UNIQUE,
    role            user_role NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at      TIMESTAMPTZ NOT NULL,
    is_revoked      BOOLEAN NOT NULL DEFAULT FALSE,
    revoked_at      TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS idx_user_sessions_token_hash ON user_sessions(token_hash);
CREATE INDEX IF NOT EXISTS idx_user_sessions_user_id ON user_sessions(user_id);

COMMENT ON TABLE user_sessions IS 'Persistent session store for authenticated admin and officer tokens.';
COMMENT ON COLUMN user_sessions.token_hash IS 'SHA-256 hex digest of the raw bearer token. Plaintext tokens are never stored.';
COMMENT ON COLUMN user_sessions.is_revoked IS 'TRUE once an officer logs out or an administrator revokes the session.';
