-- VaahanSetu local PostgreSQL initialisation
-- Safe to run against the local Docker instance (vaahansetu_local / vaahan_local).
-- Does NOT touch Neon or any shared database.

-- =====================================================================
-- 1. ENUM TYPES
-- =====================================================================
DO $$ BEGIN
  CREATE TYPE user_role                 AS ENUM ('ADMIN', 'OFFICER'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TYPE bus_status                AS ENUM ('ACTIVE', 'MAINTENANCE', 'INACTIVE'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TYPE trip_status               AS ENUM ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TYPE journey_status            AS ENUM ('REGISTERED', 'BOARDED', 'COMPLETED', 'CANCELLED', 'UNCONFIRMED', 'EXPIRED'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TYPE assignment_status         AS ENUM ('ACTIVE', 'REPLACED', 'CANCELLED'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TYPE allocation_status         AS ENUM ('PROPOSED', 'APPROVED', 'EXECUTED', 'REJECTED', 'FAILED'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TYPE allocation_assignment_type AS ENUM ('UNCHANGED', 'REASSIGNED', 'UNASSIGNED'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TYPE session_status            AS ENUM ('ACTIVE', 'CLOSED'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- =====================================================================
-- 2. MASTER TABLES
-- =====================================================================

CREATE TABLE IF NOT EXISTS users (
    user_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(120) NOT NULL,
    username       VARCHAR(80)  NOT NULL UNIQUE,
    password_hash  TEXT         NOT NULL,
    role           user_role    NOT NULL,
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS buses (
    bus_id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number    VARCHAR(30)  NOT NULL UNIQUE,
    capacity               INTEGER      NOT NULL CHECK (capacity > 0),
    status                 bus_status   NOT NULL,
    current_location       VARCHAR(150) NULL,
    rest_duration_minutes  INTEGER      NOT NULL DEFAULT 0 CHECK (rest_duration_minutes >= 0),
    rest_start             TIME         NULL,
    rest_end               TIME         NULL,
    notes                  TEXT         NULL,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CHECK (
        (rest_start IS NULL AND rest_end IS NULL)
        OR
        (rest_start IS NOT NULL AND rest_end IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS routes (
    route_id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code                  VARCHAR(30)  NOT NULL UNIQUE,
    route_name                  VARCHAR(120) NOT NULL,
    origin_name                 VARCHAR(120) NOT NULL,
    destination_name            VARCHAR(120) NOT NULL,
    estimated_duration_minutes  INTEGER      NOT NULL CHECK (estimated_duration_minutes > 0),
    is_active                   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS stops (
    stop_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_name   VARCHAR(120) NOT NULL,
    latitude    NUMERIC(9,6) NULL,
    longitude   NUMERIC(9,6) NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE
);

-- =====================================================================
-- 3. ROUTE-STOP LINKS AND SCHEDULED TRIPS
-- =====================================================================

CREATE TABLE IF NOT EXISTS route_stops (
    route_id                 BIGINT   NOT NULL REFERENCES routes(route_id)   ON DELETE CASCADE,
    stop_id                  BIGINT   NOT NULL REFERENCES stops(stop_id)     ON DELETE RESTRICT,
    stop_sequence            INTEGER  NOT NULL CHECK (stop_sequence > 0),
    scheduled_offset_minutes INTEGER  NULL CHECK (scheduled_offset_minutes >= 0),
    PRIMARY KEY (route_id, stop_sequence),
    UNIQUE (route_id, stop_id)
);

CREATE TABLE IF NOT EXISTS scheduled_trips (
    trip_id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id              BIGINT       NOT NULL REFERENCES routes(route_id) ON DELETE RESTRICT,
    service_date          DATE         NOT NULL,
    departure_time        TIMESTAMP    NOT NULL,
    expected_arrival_time TIMESTAMP    NOT NULL,
    status                trip_status  NOT NULL,
    UNIQUE (route_id, departure_time)
);

-- =====================================================================
-- 4. PLANNING SESSIONS
-- =====================================================================

CREATE TABLE IF NOT EXISTS planning_sessions (
    session_id    BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_name  VARCHAR(120)   NOT NULL,
    started_at    TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    ended_at      TIMESTAMPTZ    NULL,
    created_by    BIGINT         NULL REFERENCES users(user_id) ON DELETE SET NULL,
    status        session_status NOT NULL,
    simulation_elapsed_minutes INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS session_buses (
    session_id  BIGINT  NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    bus_id      BIGINT  NOT NULL REFERENCES buses(bus_id)                  ON DELETE CASCADE,
    PRIMARY KEY (session_id, bus_id)
);

CREATE TABLE IF NOT EXISTS session_routes (
    session_id  BIGINT  NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    route_id    BIGINT  NOT NULL REFERENCES routes(route_id)              ON DELETE CASCADE,
    PRIMARY KEY (session_id, route_id)
);

-- =====================================================================
-- 5. TRIP ASSIGNMENTS AND PASSENGER JOURNEYS
-- =====================================================================

CREATE TABLE IF NOT EXISTS trip_assignments (
    assignment_id  BIGINT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id        BIGINT            NOT NULL REFERENCES scheduled_trips(trip_id) ON DELETE CASCADE,
    bus_id         BIGINT            NOT NULL REFERENCES buses(bus_id)           ON DELETE RESTRICT,
    assigned_at    TIMESTAMPTZ       NOT NULL DEFAULT NOW(),
    assigned_by    BIGINT            NULL REFERENCES users(user_id)              ON DELETE SET NULL,
    status         assignment_status NOT NULL
);

CREATE TABLE IF NOT EXISTS passenger_journeys (
    journey_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id               BIGINT          NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    trip_id                  BIGINT          NOT NULL REFERENCES scheduled_trips(trip_id)      ON DELETE CASCADE,
    boarding_stop_id         BIGINT          NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    destination_stop_id      BIGINT          NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    passenger_count          INTEGER         NOT NULL DEFAULT 1 CHECK (passenger_count > 0),
    journey_status           journey_status  NOT NULL,
    boarding_confirmed_at    TIMESTAMPTZ     NULL,
    alighting_confirmed_at   TIMESTAMPTZ     NULL,
    submitted_at             TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    passenger_reference      VARCHAR(100)    NULL
);

-- =====================================================================
-- 6. ALLOCATION
-- =====================================================================

CREATE TABLE IF NOT EXISTS allocation_runs (
    allocation_run_id      BIGINT             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id             BIGINT             NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    created_at             TIMESTAMPTZ        NOT NULL DEFAULT NOW(),
    created_by             BIGINT             NULL REFERENCES users(user_id)                  ON DELETE SET NULL,
    status                 allocation_status  NOT NULL,
    is_simulated           BOOLEAN            NOT NULL DEFAULT FALSE,
    total_demand           INTEGER            NOT NULL DEFAULT 0 CHECK (total_demand           >= 0),
    total_accommodated     INTEGER            NOT NULL DEFAULT 0 CHECK (total_accommodated     >= 0),
    total_unmet_demand     INTEGER            NOT NULL DEFAULT 0 CHECK (total_unmet_demand     >= 0),
    total_unused_capacity  INTEGER            NOT NULL DEFAULT 0 CHECK (total_unused_capacity  >= 0),
    notes                  TEXT               NULL
);

CREATE TABLE IF NOT EXISTS allocation_assignments (
    allocation_assignment_id  BIGINT                     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_run_id         BIGINT                     NOT NULL REFERENCES allocation_runs(allocation_run_id) ON DELETE CASCADE,
    trip_id                   BIGINT                     NOT NULL REFERENCES scheduled_trips(trip_id)          ON DELETE CASCADE,
    previous_bus_id           BIGINT                     NULL REFERENCES buses(bus_id)                        ON DELETE SET NULL,
    proposed_bus_id           BIGINT                     NULL REFERENCES buses(bus_id)                        ON DELETE SET NULL,
    assignment_type           allocation_assignment_type NOT NULL,
    reason                    TEXT                       NULL,
    UNIQUE (allocation_run_id, trip_id)
);

CREATE TABLE IF NOT EXISTS segment_demand_adjustments (
    adjustment_id          BIGINT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id             BIGINT   NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    route_id               BIGINT   NOT NULL REFERENCES routes(route_id)             ON DELETE CASCADE,
    segment_start_stop_id  BIGINT   NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    segment_end_stop_id    BIGINT   NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    demand_delta            INTEGER  NOT NULL,
    is_simulated            BOOLEAN  NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (segment_start_stop_id <> segment_end_stop_id)
);

CREATE TABLE IF NOT EXISTS allocation_segment_results (
    allocation_segment_result_id  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_run_id             BIGINT  NOT NULL REFERENCES allocation_runs(allocation_run_id) ON DELETE CASCADE,
    route_id                      BIGINT  NOT NULL REFERENCES routes(route_id)                  ON DELETE RESTRICT,
    segment_start_stop_id         BIGINT  NOT NULL REFERENCES stops(stop_id)                    ON DELETE RESTRICT,
    segment_end_stop_id           BIGINT  NOT NULL REFERENCES stops(stop_id)                    ON DELETE RESTRICT,
    demand                        INTEGER NOT NULL CHECK (demand            >= 0),
    allocated_capacity            INTEGER NOT NULL CHECK (allocated_capacity  >= 0),
    accommodated                  INTEGER NOT NULL CHECK (accommodated       >= 0),
    unmet_demand                  INTEGER NOT NULL CHECK (unmet_demand       >= 0),
    unused_capacity               INTEGER NOT NULL CHECK (unused_capacity    >= 0),
    CHECK (segment_start_stop_id <> segment_end_stop_id)
);

