-- 8. TRIGGERS
-- =====================================================================
CREATE OR REPLACE FUNCTION fn_pj_check_stop_order() RETURNS TRIGGER AS $$
DECLARE
    v_route_id        BIGINT;
    v_boarding_seq    INTEGER;
    v_destination_seq INTEGER;
BEGIN
    SELECT route_id INTO v_route_id FROM scheduled_trips WHERE trip_id = NEW.trip_id;
    SELECT rs.stop_sequence INTO v_boarding_seq FROM route_stops rs
        WHERE rs.route_id = v_route_id AND rs.stop_id = NEW.boarding_stop_id;
    SELECT rs.stop_sequence INTO v_destination_seq FROM route_stops rs
        WHERE rs.route_id = v_route_id AND rs.stop_id = NEW.destination_stop_id;
    IF v_boarding_seq IS NULL OR v_destination_seq IS NULL THEN
        RAISE EXCEPTION 'Boarding/destination stops must belong to the route of trip % (route %).', NEW.trip_id, v_route_id;
    END IF;
    IF v_boarding_seq >= v_destination_seq THEN
        RAISE EXCEPTION 'Boarding stop (seq %) must precede destination stop (seq %) for trip %.', v_boarding_seq, v_destination_seq, NEW.trip_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pj_check_stop_order ON passenger_journeys;
CREATE TRIGGER trg_pj_check_stop_order
    BEFORE INSERT OR UPDATE OF boarding_stop_id, destination_stop_id, trip_id
    ON passenger_journeys
    FOR EACH ROW EXECUTE FUNCTION fn_pj_check_stop_order();

CREATE OR REPLACE FUNCTION fn_pj_confirmations() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.alighting_confirmed_at IS NOT NULL AND NEW.boarding_confirmed_at IS NOT NULL
       AND NEW.alighting_confirmed_at < NEW.boarding_confirmed_at THEN
        RAISE EXCEPTION 'alighting_confirmed_at cannot be earlier than boarding_confirmed_at (journey %).', NEW.journey_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pj_confirmations ON passenger_journeys;
CREATE TRIGGER trg_pj_confirmations
    BEFORE INSERT OR UPDATE ON passenger_journeys
    FOR EACH ROW EXECUTE FUNCTION fn_pj_confirmations();
