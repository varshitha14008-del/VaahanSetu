-- =====================================================================
-- 1. ENUM TYPES  (Section 5 of the Database & Models doc)
-- =====================================================================
CREATE TYPE user_role                 AS ENUM ('ADMIN', 'OFFICER');
CREATE TYPE bus_status                AS ENUM ('ACTIVE', 'MAINTENANCE', 'INACTIVE');
CREATE TYPE trip_status               AS ENUM ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED');
CREATE TYPE journey_status            AS ENUM ('REGISTERED', 'BOARDED', 'COMPLETED',
                                              'CANCELLED', 'UNCONFIRMED', 'EXPIRED');
CREATE TYPE assignment_status         AS ENUM ('ACTIVE', 'REPLACED', 'CANCELLED');
CREATE TYPE allocation_status         AS ENUM ('PROPOSED', 'APPROVED', 'EXECUTED',
                                              'REJECTED', 'FAILED');
CREATE TYPE allocation_assignment_type AS ENUM ('UNCHANGED', 'REASSIGNED', 'UNASSIGNED');
CREATE TYPE session_status            AS ENUM ('ACTIVE', 'CLOSED');

COMMENT ON TYPE user_role                  IS 'VaahanSetu: ADMIN or OFFICER only (no passenger role here).';
COMMENT ON TYPE bus_status                 IS 'VaahanSetu bus state: ACTIVE / MAINTENANCE / INACTIVE.';
COMMENT ON TYPE trip_status                IS 'VaahanSetu scheduled-trip lifecycle state.';
COMMENT ON TYPE journey_status             IS 'VaahanSetu passenger-journey lifecycle (incl. UNCONFIRMED / EXPIRED).';
COMMENT ON TYPE assignment_status          IS 'VaahanSetu trip-assignment lifecycle.';
COMMENT ON TYPE allocation_status          IS 'VaahanSetu allocation-run lifecycle.';
COMMENT ON TYPE allocation_assignment_type IS 'VaahanSetu allocation outcome type per trip.';
COMMENT ON TYPE session_status             IS 'VaahanSetu planning-session state: ACTIVE or CLOSED.';


-- =====================================================================
-- 2. MASTER TABLES: users, buses, routes, stops
-- =====================================================================

-- 2.1 users ---------------------------------------------------------
CREATE TABLE users (
    user_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(120) NOT NULL,
    username       VARCHAR(80)  NOT NULL UNIQUE,
    password_hash  TEXT         NOT NULL,                 -- never store plaintext
    role           user_role    NOT NULL,                 -- ADMIN or OFFICER
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
COMMENT ON TABLE  users IS 'VaahanSetu admin/officer accounts. Passengers are NOT stored here (see SRS section 5 / 9).';
COMMENT ON COLUMN users.password_hash IS 'Bcrypt/Argon2 hash. Plaintext passwords are forbidden.';
COMMENT ON COLUMN users.is_active     IS 'Disable an account without deleting it.';

-- 2.2 buses ---------------------------------------------------------
CREATE TABLE buses (
    bus_id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number    VARCHAR(30)  NOT NULL UNIQUE,
    capacity               INTEGER      NOT NULL CHECK (capacity > 0),
    status                 bus_status   NOT NULL,
    current_location       VARCHAR(150) NULL, -- prototype: depot or last endpoint
    rest_duration_minutes  INTEGER      NOT NULL DEFAULT 0 CHECK (rest_duration_minutes >= 0),
    rest_start             TIME         NULL, -- daily rest-slot start (clock time)
    rest_end               TIME         NULL, -- daily rest-slot end; may be earlier than rest_start for overnight rests
    notes                  TEXT         NULL,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CHECK (
        (rest_start IS NULL AND rest_end IS NULL)
        OR
        (rest_start IS NOT NULL AND rest_end IS NOT NULL)
    )
);

COMMENT ON TABLE buses IS 'VaahanSetu bus fleet master data.';
COMMENT ON COLUMN buses.capacity IS 'Maximum permitted passengers.';
COMMENT ON COLUMN buses.rest_duration_minutes IS 'Minimum rest interval a bus must take after a trip, in minutes.';
COMMENT ON COLUMN buses.rest_start IS 'Daily rest-slot start (clock time, NULL = no fixed slot). May be later than rest_end for overnight rests.';
COMMENT ON COLUMN buses.rest_end IS 'Daily rest-slot end (clock time, NULL = no fixed slot). May be earlier than rest_start for overnight rests.';

-- 2.3 routes --------------------------------------------------------
CREATE TABLE routes (
    route_id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code                  VARCHAR(30)  NOT NULL UNIQUE,
    route_name                  VARCHAR(120) NOT NULL,
    origin_name                 VARCHAR(120) NOT NULL,
    destination_name            VARCHAR(120) NOT NULL,
    estimated_duration_minutes  INTEGER      NOT NULL CHECK (estimated_duration_minutes > 0),
    is_active                   BOOLEAN      NOT NULL DEFAULT TRUE
);
COMMENT ON TABLE routes IS 'Fixed routes. Path is never changed by the system; only the bus-to-trip assignment is.';
COMMENT ON COLUMN routes.estimated_duration_minutes IS 'Predetermined route duration (prototype convention; no per-trip override).';

-- 2.4 stops ---------------------------------------------------------
CREATE TABLE stops (
    stop_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_name   VARCHAR(120) NOT NULL,
    latitude    NUMERIC(9,6) NULL,                        -- optional heatmap coord
    longitude   NUMERIC(9,6) NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE
);
COMMENT ON TABLE stops IS 'Boarding / alighting / intermediate points. Optional lat/long supports the optional heatmap.';


-- =====================================================================
-- 3. ROUTE-STOP LINKS AND SCHEDULED TRIPS
-- =====================================================================

-- 2.5 route_stops ---------------------------------------------------
CREATE TABLE route_stops (
    route_id                 BIGINT   NOT NULL REFERENCES routes(route_id)   ON DELETE CASCADE,
    stop_id                  BIGINT   NOT NULL REFERENCES stops(stop_id)     ON DELETE RESTRICT,
    stop_sequence            INTEGER  NOT NULL CHECK (stop_sequence > 0),
    scheduled_offset_minutes INTEGER  NULL CHECK (scheduled_offset_minutes >= 0),
    PRIMARY KEY (route_id, stop_sequence),
    UNIQUE (route_id, stop_id)         -- simplified model: no repeated stop per route
);
COMMENT ON TABLE route_stops IS 'Ordered stop list per route. Each route must have >= 2 rows (enforced by trigger route_stops_min_two).';
COMMENT ON COLUMN route_stops.stop_sequence            IS '1-based order of the stop on the route. Boarding stop must precede destination stop (validated in service layer).';
COMMENT ON COLUMN route_stops.scheduled_offset_minutes IS 'Optional minutes after route start for display only.';

-- 2.6 scheduled_trips ----------------------------------------------
CREATE TABLE scheduled_trips (
    trip_id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id              BIGINT       NOT NULL REFERENCES routes(route_id) ON DELETE RESTRICT,
    service_date          DATE         NOT NULL,
    departure_time        TIMESTAMP    NOT NULL,          -- PDF uses TIMESTAMP (no TZ) here
    expected_arrival_time TIMESTAMP    NOT NULL,          -- normally departure + route.estimated_duration_minutes
    status                trip_status  NOT NULL,
    UNIQUE (route_id, departure_time)
);
COMMENT ON TABLE  scheduled_trips IS 'Predetermined departures on a fixed route. PDF: avoid mixing TIMESTAMP and TIMESTAMPTZ; this table uses plain TIMESTAMP per the spec.';
COMMENT ON COLUMN scheduled_trips.expected_arrival_time IS 'For the prototype this equals departure_time + routes.estimated_duration_minutes (no per-trip override).';
COMMENT ON COLUMN scheduled_trips.service_date          IS 'Calendar date of the departure, denormalised for fast filtering by date.';


-- =====================================================================
-- 4. PLANNING SESSIONS AND SESSION-LEVEL SELECTIONS
-- =====================================================================

-- 2.8 planning_sessions  (declared before session_buses / session_routes) -
CREATE TABLE planning_sessions (
    session_id    BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_name  VARCHAR(120)   NOT NULL,
    started_at    TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    ended_at      TIMESTAMPTZ    NULL,
    created_by    BIGINT         NULL REFERENCES users(user_id) ON DELETE SET NULL,
    status        session_status NOT NULL
);
COMMENT ON TABLE  planning_sessions IS 'One active session at a time. Enforced by partial unique index uq_one_active_session.';
COMMENT ON COLUMN planning_sessions.ended_at IS 'NULL while the session is ACTIVE; set when status becomes CLOSED.';

-- 2.9 session_buses -------------------------------------------------
CREATE TABLE session_buses (
    session_id  BIGINT  NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    bus_id      BIGINT  NOT NULL REFERENCES buses(bus_id)                  ON DELETE CASCADE,
    PRIMARY KEY (session_id, bus_id)
);
COMMENT ON TABLE session_buses IS 'Many-to-many: buses selected for a planning session. Only these participate in its allocation.';

-- 2.10 session_routes ----------------------------------------------
CREATE TABLE session_routes (
    session_id  BIGINT  NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    route_id    BIGINT  NOT NULL REFERENCES routes(route_id)              ON DELETE CASCADE,
    PRIMARY KEY (session_id, route_id)
);
COMMENT ON TABLE session_routes IS 'Many-to-many: routes selected for a planning session. Only these participate in its allocation.';


-- =====================================================================
-- 5. TRIP ASSIGNMENTS AND PASSENGER JOURNEYS
-- =====================================================================

-- 2.7 trip_assignments ---------------------------------------------
CREATE TABLE trip_assignments (
    assignment_id  BIGINT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id        BIGINT            NOT NULL REFERENCES scheduled_trips(trip_id) ON DELETE CASCADE,
    bus_id         BIGINT            NOT NULL REFERENCES buses(bus_id)           ON DELETE RESTRICT,
    assigned_at    TIMESTAMPTZ       NOT NULL DEFAULT NOW(),
    assigned_by    BIGINT            NULL REFERENCES users(user_id)              ON DELETE SET NULL,
    status         assignment_status NOT NULL
);
COMMENT ON TABLE  trip_assignments IS 'Baseline / current bus-to-trip assignments. At most one ACTIVE assignment per trip (see partial unique index uq_trip_one_active_assignment).';
COMMENT ON COLUMN trip_assignments.status IS 'Old assignments are marked REPLACED/CANCELLED; they are NOT deleted (history is preserved).';

-- 2.11 passenger_journeys ------------------------------------------
CREATE TABLE passenger_journeys (
    journey_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id               BIGINT          NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    trip_id                  BIGINT          NOT NULL REFERENCES scheduled_trips(trip_id)      ON DELETE CASCADE,
    boarding_stop_id         BIGINT          NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    destination_stop_id      BIGINT          NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    passenger_count          INTEGER         NOT NULL DEFAULT 1 CHECK (passenger_count > 0),
    journey_status           journey_status  NOT NULL,
    boarding_confirmed_at    TIMESTAMPTZ     NULL,
    alighting_confirmed_at   TIMESTAMPTZ     NULL,
    submitted_at             TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    passenger_reference      VARCHAR(100)    NULL
);
COMMENT ON TABLE  passenger_journeys IS 'Passenger journey registrations captured via the mobile interface.';
COMMENT ON COLUMN passenger_journeys.boarding_stop_id    IS 'FK stops. MUST belong to the trip route and precede destination (validated by trigger pj_check_stop_order).';
COMMENT ON COLUMN passenger_journeys.destination_stop_id IS 'FK stops. MUST belong to the trip route and follow boarding (validated by trigger pj_check_stop_order).';
COMMENT ON COLUMN passenger_journeys.passenger_count     IS 'People represented by this registration (>=1).';
COMMENT ON COLUMN passenger_journeys.journey_status      IS 'Includes UNCONFIRMED / EXPIRED -- unconfirmed mobile registrations are NOT treated as guaranteed occupancy.';
COMMENT ON COLUMN passenger_journeys.passenger_reference IS 'Optional non-sensitive token a passenger can use to manage only their own journey (no passenger login assumed).';


-- =====================================================================
-- 6. ALLOCATION RUNS, ALLOCATION ASSIGNMENTS, SEGMENT DEMAND ADJUSTMENTS
-- =====================================================================

-- 2.12 allocation_runs ---------------------------------------------
CREATE TABLE allocation_runs (
    allocation_run_id      BIGINT             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id             BIGINT             NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    created_at             TIMESTAMPTZ        NOT NULL DEFAULT NOW(),
    created_by             BIGINT             NULL REFERENCES users(user_id)                  ON DELETE SET NULL,
    status                 allocation_status  NOT NULL,
    is_simulated           BOOLEAN            NOT NULL DEFAULT FALSE,
    total_demand           INTEGER            NOT NULL DEFAULT 0 CHECK (total_demand           >= 0),
    total_accommodated     INTEGER            NOT NULL DEFAULT 0 CHECK (total_accommodated     >= 0),
    total_unmet_demand     INTEGER            NOT NULL DEFAULT 0 CHECK (total_unmet_demand     >= 0),
    total_unused_capacity  INTEGER            NOT NULL DEFAULT 0 CHECK (total_unused_capacity  >= 0),
    notes                  TEXT               NULL
);
COMMENT ON TABLE  allocation_runs IS 'One allocation calculation per run. Baseline and proposed allocations are stored as separate runs.';
COMMENT ON COLUMN allocation_runs.is_simulated IS 'TRUE if the demand snapshot used here came from a simulation pass.';
COMMENT ON COLUMN allocation_runs.total_demand IS 'Aggregation convention must be defined by the team (per-segment sum vs unique journeys).';

-- 2.13 allocation_assignments --------------------------------------
CREATE TABLE allocation_assignments (
    allocation_assignment_id  BIGINT                     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_run_id         BIGINT                     NOT NULL REFERENCES allocation_runs(allocation_run_id) ON DELETE CASCADE,
    trip_id                   BIGINT                     NOT NULL REFERENCES scheduled_trips(trip_id)          ON DELETE CASCADE,
    previous_bus_id           BIGINT                     NULL REFERENCES buses(bus_id)                        ON DELETE SET NULL,
    proposed_bus_id           BIGINT                     NULL REFERENCES buses(bus_id)                        ON DELETE SET NULL,
    assignment_type           allocation_assignment_type NOT NULL,
    reason                    TEXT                       NULL,
    UNIQUE (allocation_run_id, trip_id)
);
COMMENT ON TABLE  allocation_assignments IS 'Per-trip outcome of an allocation run. UNCHANGED / REASSIGNED / UNASSIGNED.';
COMMENT ON COLUMN allocation_assignments.previous_bus_id IS 'Baseline bus (NULL if there was no prior assignment).';
COMMENT ON COLUMN allocation_assignments.proposed_bus_id IS 'Proposed bus for this trip. NULL = unassigned.';
COMMENT ON COLUMN allocation_assignments.assignment_type IS 'UNCHANGED = keep prior bus; REASSIGNED = swap to a different bus; UNASSIGNED = no eligible bus.';

-- 2.14 segment_demand_adjustments ----------------------------------
CREATE TABLE segment_demand_adjustments (
    adjustment_id          BIGINT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id             BIGINT   NOT NULL REFERENCES planning_sessions(session_id) ON DELETE CASCADE,
    route_id               BIGINT   NOT NULL REFERENCES routes(route_id)             ON DELETE CASCADE,
    segment_start_stop_id  BIGINT   NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    segment_end_stop_id    BIGINT   NOT NULL REFERENCES stops(stop_id)               ON DELETE RESTRICT,
    demand_delta            INTEGER  NOT NULL,                 -- simulated +/- (5..10 magnitude per SRS F18)
    is_simulated            BOOLEAN  NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (segment_start_stop_id <> segment_end_stop_id)
);
COMMENT ON TABLE  segment_demand_adjustments IS 'Simulated +/- adjustments to segment demand, kept SEPARATE from raw passenger_journeys (per SRS F18 / F19).';
COMMENT ON COLUMN segment_demand_adjustments.demand_delta IS 'Signed change. Magnitude 5..10 per SRS. Application must clamp resulting demand at 0.';
COMMENT ON COLUMN segment_demand_adjustments.is_simulated IS 'Always TRUE here. Column retained for clarity and cross-filtering.';


-- =====================================================================
-- 7. OPTIONAL allocation_segment_results (recommended)
-- =====================================================================
CREATE TABLE allocation_segment_results (
    allocation_segment_result_id  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_run_id             BIGINT  NOT NULL REFERENCES allocation_runs(allocation_run_id) ON DELETE CASCADE,
    route_id                      BIGINT  NOT NULL REFERENCES routes(route_id)                  ON DELETE RESTRICT,
    segment_start_stop_id         BIGINT  NOT NULL REFERENCES stops(stop_id)                    ON DELETE RESTRICT,
    segment_end_stop_id           BIGINT  NOT NULL REFERENCES stops(stop_id)                    ON DELETE RESTRICT,
    demand                        INTEGER NOT NULL CHECK (demand            >= 0),
    allocated_capacity            INTEGER NOT NULL CHECK (allocated_capacity  >= 0),
    accommodated                  INTEGER NOT NULL CHECK (accommodated       >= 0),
    unmet_demand                  INTEGER NOT NULL CHECK (unmet_demand       >= 0),
    unused_capacity               INTEGER NOT NULL CHECK (unused_capacity    >= 0),
    CHECK (segment_start_stop_id <> segment_end_stop_id)
);
COMMENT ON TABLE allocation_segment_results IS 'Per-segment outcome of an allocation run (recommended). One row per (run, route, consecutive-stop pair).';
COMMENT ON COLUMN allocation_segment_results.accommodated IS '= LEAST(demand, allocated_capacity).';
COMMENT ON COLUMN allocation_segment_results.unmet_demand IS '= GREATEST(0, demand - allocated_capacity).';
COMMENT ON COLUMN allocation_segment_results.unused_capacity IS '= GREATEST(0, allocated_capacity - demand).';


