-- At most one ACTIVE assignment per trip (PDF 2.7 / Rule "At most one current bus per trip")
CREATE UNIQUE INDEX uq_trip_one_active_assignment
    ON trip_assignments (trip_id)
    WHERE status = 'ACTIVE';

-- Enforce one ACTIVE planning session at a time (PDF 2.8 / SRS constraint).
-- NOTE: indexing on a CONSTANT expression is required so every ACTIVE row
-- maps to the same key. Indexing on session_id would NOT enforce this rule
-- because session_id is unique per row by definition.
CREATE UNIQUE INDEX uq_one_active_session
    ON planning_sessions ((1))
    WHERE status = 'ACTIVE';

